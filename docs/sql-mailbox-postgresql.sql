-- Tables for Neo-PostOffice's SQL mailbox type, PostgreSQL version.
--
-- The SQL mailbox reads mail that another program has put into these
-- tables; tools/po-sqldeliver does that from a mail server. The layout is
-- reconstructed from the queries of PostOffice 0.7.3, whose own schema was
-- never published. Column names must stay as they are.
--
--   psql -d postoffice -f docs/sql-mailbox-postgresql.sql

CREATE TABLE messages (
    msgid     integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folder    text     NOT NULL DEFAULT 'Inbox', -- PostOffice folder name
    namefrom  text     NOT NULL DEFAULT '',      -- sender's display name
    mailfrom  text     NOT NULL DEFAULT '',      -- sender's address
    mailto    text     NOT NULL DEFAULT '',      -- recipient(s)
    subject   text     NOT NULL DEFAULT '',
    received  text     NOT NULL DEFAULT '',      -- shown as the message date
    msgread   smallint NOT NULL DEFAULT 0,       -- set to 1 when opened
    body      text     NOT NULL                  -- the whole raw message, encoded:
                                                 -- bytes other than letters, digits,
                                                 -- space and .,:;/!? as @ + 2 hex digits
);
CREATE INDEX messages_folder ON messages (folder);

-- One row per header line (filled by po-sqldeliver -H; used by the
-- original server-side tools, not by the PostOffice client).
CREATE TABLE headers (
    msgid  integer NOT NULL REFERENCES messages ON DELETE CASCADE,
    name   text    NOT NULL,
    value  text
);
CREATE INDEX headers_msgid ON headers (msgid);
CREATE INDEX headers_name ON headers (name);
